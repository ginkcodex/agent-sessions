// Fails to compile when WailsAppBinding gains a method APP_METHODS lacks.
type MissingMethods = Exclude<keyof WailsAppBinding, (typeof APP_METHODS)[number]>;
const complete: [MissingMethods] extends [never] ? true : MissingMethods = true;
void complete;

export type AppCall = (method: string, ...args: unknown[]) => Promise<any>;

/** Builds the binding; each method forwards its arguments to call. */
export function createAppBinding(call: AppCall = callApp): WailsAppBinding {
  const binding: Record<string, (...args: unknown[]) => Promise<any>> = {};
  for (const method of APP_METHODS) {
    binding[method] = (...args: unknown[]) => call(method, ...args);
  }
  return binding as unknown as WailsAppBinding;
}
